/** The fixture as the bytes the wrapper is handed, which is how the bridge's base64 arrives. */
function fixtureBytes(): Uint8Array {
  return new Uint8Array(Buffer.from(DOCX_FIXTURE_BASE64, 'base64'))
}

const ZIP_SIGNATURE = [0x50, 0x4b, 0x03, 0x04]

function theFixtureIsAContainer() {
  const bytes = fixtureBytes()
  assert.deepEqual(Array.from(bytes.slice(0, 4)), ZIP_SIGNATURE, 'the fixture starts with a zip header')
  // No assertion below is worth anything if this constant were empty or mis-encoded, so it is pinned
  // here rather than trusted.
  assert.ok(bytes.length > 1000, 'and it carries a whole container')
  results.push('the fixture decodes to a real zip container')
}

async function aWordDocumentBecomesItsParagraphs() {
  const conversion = await docxToHtml(fixtureBytes())

  assert.equal(conversion.ok, true, `a real docx converts: ${conversion.ok ? '' : conversion.message}`)
  if (!conversion.ok) return
  assert.ok(conversion.html.includes('Hello from the document.'), 'the first paragraph is in the html')
  assert.ok(conversion.html.includes('Second paragraph.'), 'and the second one')
  assert.ok(conversion.html.includes('<p>'), 'as elements rather than as bare text')
  results.push('a docx converts to html carrying its own paragraph text')
}

async function bytesThatAreNotAContainerAreRefusedInWords() {
  const notAContainer = new TextEncoder().encode('this is plainly not a Word document')

  const conversion = await docxToHtml(notAContainer)

  assert.equal(conversion.ok, false, 'plain text is not a docx')
  if (conversion.ok) return
  assert.ok(conversion.message.includes('Word'), `the refusal names the format: ${conversion.message}`)
  assert.ok(conversion.message.trim().length > 10, 'and reads as a sentence rather than as a code')
  results.push('bytes that are not a container are refused in this app’s own wording')
}

async function anEmptyBufferIsRefusedTheSameWay() {
  const conversion = await docxToHtml(new Uint8Array(0))

  assert.equal(conversion.ok, false, 'an empty buffer is not a docx either')
  results.push('an empty buffer is refused rather than converted to empty html')
}

// ---------------------------------------------------------------- harness

async function main() {
  await step('fixture: container', theFixtureIsAContainer)
  await step('convert: paragraphs', aWordDocumentBecomesItsParagraphs)
  await step('refuse: not a container', bytesThatAreNotAContainerAreRefusedInWords)
  await step('refuse: empty', anEmptyBufferIsRefusedTheSameWay)

  console.log(`docx convert: ${results.length} passed`)
  for (const r of results) console.log(`  pass: ${r}`)
}

void main().catch((err) => {
  console.error('DOCX CONVERT TEST FAILED:', err)
  process.exit(1)
})
