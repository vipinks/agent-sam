/**
 * The docx conversion wrapper, through the real mammoth.
 *
 * The claim being made is that this app can turn a Word container into HTML, and the only evidence for
 * it is mammoth itself reading a real one. So the fixture is a genuine `.docx` — four parts, built by
 * `tests/probes/make-docx-fixture.mjs` and carried here as base64 — and the assertion is made on the
 * paragraph text mammoth's own reader produces. A stub would prove the plumbing and nothing about the
 * format, which is the half of this that can actually be wrong.
 *
 * The refusal is the other half: bytes that are not a container at all must come back as a sentence
 * rather than as mammoth's own complaint about a central directory. That wording is this app's, which
 * is why it is asserted here rather than left to the browser to render.
 */
